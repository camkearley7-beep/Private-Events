#!/usr/bin/env bash
# Builds the paste-ready Elementor files (dist/) and a standalone preview
# (preview.html) from src/. Needs only bash + python3 (stdlib).
# Re-run after editing anything in src/ or adding fonts to fonts/.
set -euo pipefail
cd "$(dirname "$0")"

python3 - <<'PY'
import json, pathlib, re, shutil
ROOT = pathlib.Path('.').resolve()
src = lambda n: (ROOT / 'src' / n).read_text()
IMG_LIVE = 'https://thebogeyclub.com/wp-content/uploads/bogey-home'
FONTS_LIVE = 'https://thebogeyclub.com/wp-content/uploads/fonts'

# Only declare the Satoshi weights we actually have files for.
have = {p.name for p in (ROOT / 'fonts').glob('*.woff2')}
head = src('head.html')
for f in ('Satoshi-Regular.woff2', 'Satoshi-Medium.woff2', 'Satoshi-Bold.woff2'):
    if f not in have:
        head = re.sub(r'@font-face [^\n]*' + re.escape(f) + r'[^\n]*\n', '', head)
        head = re.sub(r'<link rel="preload"[^>]*' + re.escape(f) + r'[^>]*>\n', '', head)

if 'Satoshi-Regular.woff2' not in have or 'Satoshi-Medium.woff2' not in have:
    # Without Regular/Medium, keep body text on the system font rather than faking it with Bold.
    head = head.replace('</style>', "html .tt { --font-body: system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif; }\n</style>", 1)
schema = json.loads(src('schema.jsonld'))
schema_tag = '<script type="application/ld+json">\n' + json.dumps(schema, indent=2, ensure_ascii=False) + '\n</script>\n'
css, js = src('tt.css'), src('tt.js')
header, home, footer = src('header.html'), src('home.html'), src('footer.html')

live = lambda s: s.replace('{{IMG}}', IMG_LIVE).replace('{{FONTS}}', FONTS_LIVE)
dist = ROOT / 'dist'; dist.mkdir(exist_ok=True)
files = {
  '00-head.html': live(head),
  '01-styles.css': css,
  '02-script.html': '<script>\n' + js + '</script>\n',
  '03-header.html': live(header),
  '04-home.html': live(home),
  '05-footer.html': live(footer),
  '06-schema.html': schema_tag,
}
for n, body in files.items(): (dist / n).write_text(body)

# Files to upload to WordPress (real assets only; concept renders are never shipped).
up = dist / 'uploads'; (up / 'bogey-home').mkdir(parents=True, exist_ok=True); (up / 'fonts').mkdir(exist_ok=True)
A = ROOT.parent / 'concepts' / 'club' / 'assets'
for s, d in [('bogey-club-logo-pine.png', 'bogey-club-logo-pine.png'), ('bogey-club-logo-white.png', 'bogey-club-logo-white.png'),
             ('karaoke-real-duet.jpg', 'karaoke-the-bogey-club-newmarket.jpg')]:
    shutil.copy(A / s, up / 'bogey-home' / d)
for f in have: shutil.copy(ROOT / 'fonts' / f, up / 'fonts' / f)

# Preview: same markup, concept renders standing in for photos (labelled).
pa = ROOT / 'preview-assets'; pa.mkdir(exist_ok=True)
for s, d in [('render-bay-close.jpg', 'golf-simulator-bay-the-bogey-club-newmarket.jpg'),
             ('render-bay-tall.jpg', 'golf-simulator-bay-the-bogey-club-newmarket-mobile.jpg'),
             ('render-course.jpg', 'golfzon-simulator-screen-the-bogey-club.jpg'),
             ('render-pour.jpg', 'draft-beer-bar-the-bogey-club-newmarket.jpg'),
             ('render-pour-tall.jpg', 'draft-beer-bar-the-bogey-club-newmarket-mobile.jpg'),
             ('render-upstairs.jpg', 'private-event-space-the-bogey-club-newmarket.jpg'),
             ('render-upstairs-tall.jpg', 'private-event-space-the-bogey-club-newmarket-mobile.jpg')]:
    shutil.copy(A / s, pa / d)
for f in (up / 'bogey-home').iterdir(): shutil.copy(f, pa / f.name)
prev = lambda s: s.replace('{{IMG}}', 'preview-assets').replace('{{FONTS}}', 'fonts')
label_css = ('[data-photo]::before{content:attr(data-photo);position:absolute;z-index:6;top:14px;right:14px;'
             'font:500 11px/1 Satoshi,system-ui,sans-serif;letter-spacing:.04em;color:#fff;background:rgba(35,62,49,.85);padding:6px 9px;border-radius:4px}'
             '.tt .hero[data-photo]::before{top:14px}')
news_demo = '<div class="news"><span>Existing newsletter widget goes here</span><b>Join</b></div>'
page = f'''<!doctype html>
<html lang="en-CA">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>The Bogey Club | Golf Simulator Sports Bar in Newmarket</title>
<meta name="description" content="Four Golfzon simulators, two full bars, cold beer on tap, karaoke and private event space in Newmarket, Ontario. Book a bay or plan your party.">
<link rel="canonical" href="https://thebogeyclub.com/">
<meta name="robots" content="noindex">
{prev(head)}<style>
html {{ scroll-behavior: smooth; }}
body {{ margin: 0; background: #FFFFFF; }}
{css}
{label_css}
</style>
{schema_tag}</head>
<body>
<!-- PREVIEW BUILD — generated by build.sh. Grey-labelled images are concept renders. -->
{prev(header)}
<main>
{prev(home)}
</main>
{prev(footer).replace('<!--BCH:NEWSLETTER-->', news_demo)}
<script>
{js}</script>
</body>
</html>
'''
(ROOT / 'preview.html').write_text(page)
print('built dist/ (' + str(len(files)) + ' files + uploads/) and preview.html; fonts:', sorted(have))
PY
