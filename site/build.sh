#!/usr/bin/env bash
# Builds the paste-ready Elementor files (dist/) and a standalone preview
# (preview.html) from src/. Needs only bash + python3 (stdlib).
# Re-run after editing anything in src/ or adding fonts to fonts/.
set -euo pipefail
cd "$(dirname "$0")"

python3 - <<'PY'
import json, pathlib, re, shutil
ROOT = pathlib.Path('.').resolve()
src = lambda n: (ROOT / 'src' / n).read_text()
IMG_LIVE = 'https://thebogeyclub.com/wp-content/uploads/bogey-home'
FONTS_LIVE = 'https://thebogeyclub.com/wp-content/uploads/fonts'

# Only declare the Satoshi weights we actually have files for.
have = {p.name for p in (ROOT / 'fonts').glob('*.woff2')}
head = src('head.html')
for f in ('Satoshi-Variable.woff2',):
    if f not in have:
        head = re.sub(r'@font-face [^\n]*' + re.escape(f) + r'[^\n]*\n', '', head)
        head = re.sub(r'<link rel="preload"[^>]*' + re.escape(f) + r'[^>]*>\n', '', head)

if 'Satoshi-Variable.woff2' not in have:
    # Without Regular/Medium, keep body text on the system font rather than faking it with Bold.
    head = head.replace('</style>', "html .tt { --font-body: system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif; }\n</style>", 1)
schema = json.loads(src('schema.jsonld'))
schema_tag = '<script type="application/ld+json">\n' + json.dumps(schema, indent=2, ensure_ascii=False) + '\n</script>\n'
css, js = src('tt.css'), src('tt.js')
header, home, footer = src('header.html'), src('home.html'), src('footer.html')

live = lambda s: s.replace('{{IMG}}', IMG_LIVE).replace('{{FONTS}}', FONTS_LIVE)
dist = ROOT / 'dist'; dist.mkdir(exist_ok=True)
files = {
  '00-head.html': live(head),
  '01-styles.css': css,
  '02-script.html': '<script>\n' + js + '</script>\n',
  '03-header.html': live(header),
  '04-home.html': live(home),
  '05-footer.html': live(footer),
  '06-schema.html': schema_tag,
}
for n, body in files.items(): (dist / n).write_text(body)

# Files to upload to WordPress (real assets only; concept renders are never shipped).
up = dist / 'uploads'; (up / 'bogey-home').mkdir(parents=True, exist_ok=True); (up / 'fonts').mkdir(exist_ok=True)
A = ROOT.parent / 'concepts' / 'club' / 'assets'
for s, d in [('bogey-club-logo.png', 'bogey-club-logo.png')]:
    shutil.copy(A / s, up / 'bogey-home' / d)
for f in have: shutil.copy(ROOT / 'fonts' / f, up / 'fonts' / f)

# Preview: same markup, concept renders standing in for photos (labelled).
pa = ROOT / 'preview-assets'; pa.mkdir(exist_ok=True)
for f in (up / 'bogey-home').iterdir(): shutil.copy(f, pa / f.name)
prev = lambda s: s.replace('{{IMG}}', 'preview-assets').replace('{{FONTS}}', 'fonts')
label_css = ('[data-photo]::before{content:attr(data-photo);position:absolute;z-index:6;top:14px;right:14px;'
             'font:500 11px/1 Satoshi,system-ui,sans-serif;letter-spacing:.04em;color:#fff;background:rgba(35,62,49,.85);padding:6px 9px;border-radius:4px}'
             '.tt .hero[data-photo]::before{top:14px}')
news_demo = '<div class="news"><span>Existing newsletter widget goes here</span><b>Join</b></div>'
page = f'''<!doctype html>
<html lang="en-CA">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>The Bogey Club | Golf Simulator Sports Bar in Newmarket</title>
<meta name="description" content="Four Golfzon simulators, two full bars, cold beer on tap, karaoke and private event space in Newmarket, Ontario. Book a bay or plan your party.">
<link rel="canonical" href="https://thebogeyclub.com/">
<meta name="robots" content="noindex">
{prev(head)}<style>
html {{ scroll-behavior: smooth; }}
body {{ margin: 0; background: #FFFFFF; }}
{css}
{label_css}
</style>
{schema_tag}</head>
<body>
<!-- PREVIEW BUILD — generated by build.sh. Grey-labelled images are concept renders. -->
{prev(header)}
<main>
{prev(home)}
</main>
{prev(footer).replace('<!--BCH:NEWSLETTER-->', news_demo)}
<script>
{js}</script>
</body>
</html>
'''
(ROOT / 'preview.html').write_text(page)

# Complete single-file pages ---------------------------------------------
def full_page(img, fonts, extra_css='', robots='index, follow'):
    p = lambda s: s.replace('{{IMG}}', img).replace('{{FONTS}}', fonts)
    return f'''<!doctype html>
<html lang="en-CA">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>The Bogey Club | Golf Simulator Sports Bar in Newmarket</title>
<meta name="description" content="Four Golfzon simulators, two full bars, cold beer on tap, karaoke and private event space in Newmarket, Ontario. Book a bay or plan your party.">
<link rel="canonical" href="https://thebogeyclub.com/">
<meta name="robots" content="{robots}">
<meta name="theme-color" content="#FFFFFF">
<meta property="og:type" content="website">
<meta property="og:title" content="The Bogey Club | Golf Simulator Sports Bar in Newmarket">
<meta property="og:description" content="Four Golfzon simulators, two full bars, cold beer on tap, karaoke and private events in Newmarket, Ontario.">
<meta property="og:url" content="https://thebogeyclub.com/">
<meta property="og:image" content="https://thebogeyclub.com/wp-content/uploads/2026/08/Main-Area.png">
{p(head)}<style>
html {{ scroll-behavior: smooth; }}
body {{ margin: 0; background: #FFFFFF; }}
@media (prefers-reduced-motion: reduce) {{ html {{ scroll-behavior: auto; }} }}
{css}
{extra_css}
</style>
{schema_tag}</head>
<body>
{p(header)}
<main>
{p(home)}
</main>
{p(footer).replace('<!--BCH:NEWSLETTER-->', '<!-- Existing newsletter signup form goes here -->')}
<script>
{js}</script>
</body>
</html>
'''

# 0) ONE Elementor HTML widget: everything in a single paste (no <html>/<head>/<body>).
#    Use with Page Settings > Page Layout: "Elementor Canvas" (no theme header/footer).
elementor_fix = """
/* Let the widget run edge to edge inside Elementor's container/section wrappers */
.e-con:has(.tt-one), .elementor-section:has(.tt-one) .elementor-container, .elementor-column:has(.tt-one) > .elementor-widget-wrap {
  --padding-top: 0px; --padding-right: 0px; --padding-bottom: 0px; --padding-left: 0px; --gap: 0px; --content-width: 100%; --width: 100%;
  padding: 0 !important; max-width: none !important; width: 100% !important; }
.elementor-widget-html:has(.tt-one), .elementor-widget-html:has(.tt-one) > .elementor-widget-container { width: 100%; margin: 0 !important; padding: 0 !important; }
body:has(.tt-one) { margin: 0; overflow-x: clip; }
"""
one = (f"<!-- THE BOGEY CLUB HOMEPAGE: paste this whole file into ONE Elementor HTML widget.\n"
       f"     Page Settings > Page Layout = Elementor Canvas. Container: Full Width, padding 0. -->\n"
       f"<div class=\"tt-one\">\n" + live(head).split('-->', 1)[1].strip() + "\n<style>\n" + css + elementor_fix + "</style>\n"
       + live(header) + "\n" + live(home) + "\n" + live(footer).replace('<!--BCH:NEWSLETTER-->', '<!-- Existing newsletter signup form goes here -->')
       + "\n" + schema_tag + "<script>\n" + js + "</script>\n</div>\n")
import base64 as _b64
from PIL import Image as _I; import io as _io
_im = _I.open(A / 'bogey-club-logo.png'); _im = _im.resize((300, round(_im.height * 300 / _im.width)), _I.LANCZOS)
_buf = _io.BytesIO(); _im.convert('L').save(_buf, 'PNG', optimize=True)
_logo = 'data:image/png;base64,' + _b64.b64encode(_buf.getvalue()).decode()
one = one.replace(IMG_LIVE + '/bogey-club-logo.png', _logo)
if 'Satoshi-Variable.woff2' in have:
    _font = 'data:font/woff2;base64,' + _b64.b64encode((ROOT / 'fonts' / 'Satoshi-Variable.woff2').read_bytes()).decode()
    one = re.sub(r'<link rel="preload"[^>]*>\n', '', one)
    one = re.sub(r"src: url\('[^']*Satoshi-Variable\.woff2'\) format\('woff2-variations'\), url\('[^']*Satoshi-Variable\.woff2'\) format\('woff2'\)",
                 lambda m: "src: url('" + _font + "') format('woff2')", one)
(dist / 'ELEMENTOR-PASTE-THIS.html').write_text(one)

# 1) live-ready: assets load from the WordPress uploads folders
(dist / 'bogey-club-homepage.html').write_text(full_page(IMG_LIVE, FONTS_LIVE))

# 2) self-contained: fonts and images embedded as data URIs (opens anywhere)
import base64, mimetypes
def embed(html):
    def rep(m):
        path = ROOT / m.group(1)
        mt = mimetypes.guess_type(path.name)[0] or ('font/woff2' if path.suffix == '.woff2' else 'application/octet-stream')
        return 'data:' + mt + ';base64,' + base64.b64encode(path.read_bytes()).decode()
    return re.sub(r'((?:preview-assets|fonts)/[\w.-]+\.(?:jpg|png|woff2))', rep, html)
sc = full_page('preview-assets', 'fonts', label_css, robots='noindex')
sc = re.sub(r'<link rel="preload"[^>]*>\n', '', sc)
(dist / 'bogey-club-homepage-standalone.html').write_text(embed(sc))
print('built dist/ (' + str(len(files)) + ' files + uploads/) and preview.html; fonts:', sorted(have))
PY
