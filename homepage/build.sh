#!/usr/bin/env bash
# Assembles the homepage source files into:
#   preview.html  — standalone page for review/testing (open in any browser)
#   dist/         — numbered, paste-ready files for WordPress/Elementor
# Pure bash + python3 (stdlib only); no npm, no bundler. Re-run after
# editing anything in src/.
set -euo pipefail
cd "$(dirname "$0")"

python3 - <<'PY'
import json, pathlib
src = pathlib.Path("src")
read = lambda n: (src / n).read_text()

schema = json.loads(read("schema.jsonld"))           # fails loudly on invalid JSON
schema_tag = '<script type="application/ld+json">\n' + json.dumps(schema, indent=2, ensure_ascii=False) + "\n</script>\n"

fonts = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wdth,wght@12..96,75..100,600..800'
    '&family=Instrument+Serif:ital@1&family=Manrope:wght@400..800&display=swap">\n'
)

form_host = read("form-host.html").replace("<!--BCH:INTRO-->", read("form-intro.html"))
footer = read("footer.html")

dist = pathlib.Path("dist"); dist.mkdir(exist_ok=True)
files = {
    "00-head-fonts.html": fonts,
    "01-global-styles.css": read("bch.css"),
    "02-global-script.html": "<script>\n" + read("bch.js") + "</script>\n",
    "03-header.html": read("header.html"),
    "04-home-part-1.html": read("home-1.html"),
    "05-event-inquiry-intro.html": read("form-intro.html"),
    "06-home-part-2.html": read("home-2.html"),
    "07-footer.html": footer,
    "08-mobile-bookbar.html": read("bookbar.html"),
    "09-schema-homepage.html": schema_tag,
}
for name, body in files.items():
    (dist / name).write_text(body)

preview = f"""<!doctype html>
<html lang="en-CA">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>The Bogey Club | Indoor Golf, Bar, Karaoke &amp; Events in Newmarket</title>
<meta name="description" content="Four Golfzon simulators, two full bars, cold beer on tap, karaoke and private event space in Newmarket, Ontario. Book golf or plan your party.">
<link rel="canonical" href="https://thebogeyclub.com/">
<meta name="robots" content="noindex">
<meta name="theme-color" content="#103B2D">
{fonts}<style>
html {{ scroll-behavior: smooth; }}
body {{ margin: 0; background: #F8F8F0; }}
@media (prefers-reduced-motion: reduce) {{ html {{ scroll-behavior: auto; }} }}
{read("bch.css")}</style>
{schema_tag}</head>
<body>
<!-- PREVIEW BUILD — generated by build.sh from src/. Do not edit by hand. -->
{read("header.html")}
<main>
{read("home-1.html")}
{form_host.replace("<!--BCH:FORM-->", read("preview-form.html"))}
{read("home-2.html")}
</main>
{footer.replace("<!--BCH:NEWSLETTER-->", read("preview-newsletter.html"))}
{read("bookbar.html")}
<script>
{read("bch.js")}</script>
</body>
</html>
"""
pathlib.Path("preview.html").write_text(preview)
print("built preview.html and", len(files), "files in dist/")
PY
